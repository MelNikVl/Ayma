async function main() {
  if (process.argv.includes("--remove")) {
    const r = await prisma.startup.deleteMany({ where: { isDemo: true } });
    console.log(`✓ Удалено демо-проектов: ${r.count}`);
    return;
  }

  const owner = await prisma.user.upsert({
    where: { telegramId: BigInt(-1003) },
    update: {},
    create: { telegramId: BigInt(-1003), firstName: "AYMA Demo" },
  });
  const tags = await prisma.tag.findMany({ select: { id: true, name: true } });

  for (const p of DEMOS) {
    const fundingNeed = p.breakdown.reduce((a, [, n]) => a + n, 0);
    const data = {
      name: p.name,
      shortDesc: p.shortDesc,
      fullDesc: p.fullDesc,
      status: "APPROVED" as const,
      isDemo: true,
      pageAccent: p.accent,
      preOrderEnabled: false,
      fundingNeed,
      fundingNeedDesc: p.why,
      fundingBreakdown: p.breakdown.map(([item, amount]) => ({ item, amount })) as Prisma.InputJsonValue,
      fundingContact: "Тестовый проект — контакт появится у реальной команды",
      buildMonths: p.buildMonths,
      implDays: p.implDays,
      implPrice: p.implPrice || null,
      advantages: p.advantages,
      competitors: p.competitors,
      killerFeatures: p.killer,
      secretSauce: p.sauce,
      teamInfo: p.team,
      hiring: p.hiring,
      compensation: p.compensation,
      apiStatus: p.api,
      roadmap: p.roadmap as Prisma.InputJsonValue,
    };
    const tagIds = tags.filter((t) => p.tags.includes(t.name)).map((t) => ({ id: t.id }));
    await prisma.startup.upsert({
      where: { slug: p.slug },
      update: { ...data, tags: { set: tagIds } },
      create: { ...data, slug: p.slug, founderId: owner.id, tags: { connect: tagIds } },
    });
    console.log(`✓ ${p.name}: ${fundingNeed.toLocaleString("ru-RU")} ₸`);
  }
  const ids = (await prisma.startup.findMany({ where: { isDemo: true }, select: { id: true } })).map((s) => s.id);
  await recomputeStartupScores(ids);
  console.log(`✓ Демо-проектов: ${ids.length}`);
}

main()
  .catch((e) => {
    console.error(e);
    process.exit(1);
  })
  .finally(() => prisma.$disconnect());
